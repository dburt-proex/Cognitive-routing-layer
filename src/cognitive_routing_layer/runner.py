def _missing_evidence(convergence, assumptions, register) -> list[dict[str, Any]]:
    items: list[dict[str, Any]] = []
    for option in convergence["ranking"]:
        for unmet in option["unmet_thresholds"]:
            items.append(
                {
                    "kind": "evidence_threshold",
                    "subject_ref": option["option_id"],
                    "detail": f"{option['option_id']}: {unmet}",
                }
            )
    for assumption in assumptions:
        items.append(
            {
                "kind": "undischarged_assumption",
                "subject_ref": assumption["operator_id"],
                "detail": f"{assumption['operator_id']} assumed without evidence: {assumption['assumption']}",
            }
        )
    return items


def _apply_gate(boundary_flags, audit_result, violations, partial, convergence, contradictions, signals, policy) -> dict[str, Any]:
    thresholds = policy["confidence_thresholds"]
    high_impact = bool(set(signals) & set(thresholds["high_impact_signals"]))
    required = thresholds["minimum_for_high_impact_recommendation"] if high_impact else thresholds["minimum_for_recommendation"]
    unresolved = contradiction_module.unresolved_material(contradictions)

    checks = [
        (bool(boundary_flags), "HALT", "RCP-GATE-BOUNDARY-FLAG", f"boundary flags raised: {boundary_flags}"),
        (audit_result["audit_result"] == "FAIL", "REVIEW", "RCP-GATE-AUDIT-FAIL", f"metacognitive audit failed with {audit_result['material_finding_count']} material findings"),
        (bool(violations) or bool(partial), "REVIEW", "RCP-GATE-ROUTE-INCOMPLETE", "an operator violated its contract or did not execute"),
        (convergence["selected_option_id"] is None and not convergence["tie_candidates"], "REVIEW", "RCP-GATE-EVIDENCE-INSUFFICIENT", convergence["selection_reason"]),
        (bool(unresolved), "REVIEW", "RCP-GATE-CONTRADICTION-UNRESOLVED", f"{len(unresolved)} unresolved material contradiction(s)"),
        (convergence["selected_option_id"] is not None and convergence["decision_confidence"] < required, "REVIEW", "RCP-GATE-CONFIDENCE-BELOW-THRESHOLD", f"decision confidence {convergence['decision_confidence']} is below the required {required}"),
        (bool(convergence["tie_candidates"]), "REVIEW", "RCP-GATE-MATERIAL-TIE", f"tied options {convergence['tie_candidates']}"),
    ]

    reasons = [{"reason_code": code, "detail": detail, "gate": result} for fired, result, code, detail in checks if fired]
    if any(item["gate"] == "HALT" for item in reasons):
        gate_result = "HALT"
    elif reasons:
        gate_result = "REVIEW"
    else:
        gate_result = "ALLOW"
        reasons = [{"reason_code": "RCP-GATE-ELIGIBLE-FOR-HUMAN-REVIEW", "detail": "all gates cleared", "gate": "ALLOW"}]

    return {
        "gate_result": gate_result,
        "gate_reasons": reasons,
        "confidence_threshold_applied": required,
        "high_impact_route": high_impact,
        "allow_semantics": policy["allow_semantics"],
    }


def _recommendation(convergence, gate, options) -> dict[str, Any]:
    if gate["gate_result"] == "HALT":
        return {
            "statement": "Do not proceed. A boundary condition was raised and this run cannot produce an actionable recommendation.",
            "option_id": None,
            "kind": "HALT",
        }
    if convergence["selected_option_id"] is None:
        return {
            "statement": f"No recommendation. {convergence['selection_reason']}. Route to human review with the missing-evidence list.",
            "option_id": None,
            "kind": "NO_RECOMMENDATION",
        }
    option = next(item for item in options if item["option_id"] == convergence["selected_option_id"])
    prefix = "Recommend" if gate["gate_result"] == "ALLOW" else "Provisionally recommend, pending human review"
    return {
        "statement": f"{prefix}: {option['label']}. {convergence['selection_reason']}.",
        "option_id": option["option_id"],
        "kind": "RECOMMENDATION",
    }


def _unsupported_receipt(raw, intake, normalized_hash, signals, classification, route, controls, chain, ledger_path) -> dict[str, Any]:
    receipt = {
        "receipt_version": "0.1.0",
        "run_id": raw["run_id"],
        "run_timestamp": raw["run_timestamp"],
        "problem_statement": intake["problem_statement"],
        "normalized_intake_hash": normalized_hash,
        "signals": signals,
        "classification": classification,
        "versions": {
            "policy_id": controls["policy"]["policy_id"],
            "policy_version": controls["policy"]["version"],
            "operator_registry_id": controls["registry"]["registry_id"],
            "operator_registry_version": controls["registry"]["version"],
            "operator_registry_sha256": controls["checksums"]["operator_registry_sha256"],
            "routing_policy_sha256": controls["checksums"]["routing_policy_sha256"],
        },
        "route": route,
        "evidence_used": [],
        "operator_conclusions": [],
        "assumptions": [],
        "contradictions": [],
        "missing_evidence": [
            {"kind": "coverage_gap", "subject_ref": "classification", "detail": route["coverage_gap_statement"]}
        ],
        "confidence_by_operator": [],
        "convergence": {
            "ranking": [],
            "selected_option_id": None,
            "rejected_alternatives": [],
            "decision_confidence": 0.0,
            "decision_confidence_label": controls["policy"]["confidence_model"]["label"],
        },
        "metacognitive_audit": {
            "operator_id": "metacognitive",
            "audit_result": "FAIL",
            "material_finding_count": 1,
            "findings": [
                {
                    "finding_id": "MC-F1",
                    "phase": "PLAN",
                    "severity": "material",
                    "detail": "no supported route exists for this classification",
                }
            ],
            "coverage": {"planned_operators": [], "executed_operators": [], "route_depth": 0},
        },
        "gate": {
            "gate_result": "REVIEW",
            "gate_reasons": [
                {
                    "reason_code": route["coverage_gap_reason"],
                    "detail": route["coverage_gap_statement"],
                    "gate": "REVIEW",
                }
            ],
            "confidence_threshold_applied": 0.0,
            "high_impact_route": False,
            "allow_semantics": controls["policy"]["allow_semantics"],
        },
        "recommendation": {
            "statement": "No recommendation. The intake does not match any supported task classification, so no reasoning route was run.",
            "option_id": None,
            "kind": "NO_RECOMMENDATION",
        },
        "risks": [],
        "authorization": {
            "status": "NOT_REQUESTED",
            "reason": "no route ran, so no action can be recommended",
            "verifier": "unavailable",
            "verifier_is_authentic": False,
            "checks": [],
            "derived_from_confidence": False,
        },
        "execution": {
            "execution_outcome": "REVIEW",
            "execution_authorized": False,
            "recommendation_eligible": False,
            "authorization_status": "NOT_REQUESTED",
            "composition_rule": "confidence never grants permission; authorization never cures insufficient evidence",
        },
        "review_requirements": ["A human must supply a supported classification or extend the routing policy."],
        "next_action": "Route to the decision owner to restate the problem within a supported task classification.",
        "stage_chain": chain.records,
        "stage_chain_head": chain.head,
        "partial_execution": [],
        "record_id": f"{raw['run_id']}::UNSUPPORTED",
    }
    receipt["ledger_receipt"] = append_idempotent(ledger_path, receipt)
    return receipt


def _receipt(**kwargs) -> dict[str, Any]:
    raw = kwargs["raw"]
    controls = kwargs["controls"]
    convergence = kwargs["convergence"]
    gate = kwargs["gate"]
    audit_result = kwargs["audit_result"]
    policy = controls["policy"]

    risks: list[dict[str, Any]] = []
    for conclusion in kwargs["operator_conclusions"]:
        if conclusion["operator_id"] == "inverted":
            for mode in conclusion["structured_payload"]:
                risks.append(
                    {
                        "risk_id": mode.get("failure_mode_id"),
                        "source_operator": "inverted",
                        "statement": mode.get("statement", mode.get("precondition", "")),
                        "reversible": mode.get("reversible"),
                        "detection_signal": mode.get("detection_signal"),
                        "boundary_flag_candidate": mode.get("boundary_flag_candidate"),
                    }
                )
        if conclusion["operator_id"] == "second-order":
            for effect in conclusion["structured_payload"]:
                risks.append(
                    {
                        "risk_id": effect.get("effect_id"),
                        "source_operator": "second-order",
                        "statement": effect.get("statement", ""),
                        "reversible": None,
                        "detection_signal": None,
                        "horizon": effect.get("horizon"),
                        "affected_party": effect.get("affected_party"),
                    }
                )

    review_requirements = [reason["detail"] for reason in gate["gate_reasons"] if reason["gate"] != "ALLOW"]
    if kwargs["authorization"]["status"] in {"PENDING_CASA", "VERIFICATION_UNAVAILABLE", "DENIED"}:
        review_requirements.append(f"Authorization is {kwargs['authorization']['status']}: {kwargs['authorization']['reason']}")

    next_action = {
        "ALLOW": "Present the recommendation and its receipt to the decision owner for approval.",
        "REVIEW": "Route to the decision owner with the missing-evidence and contradiction lists before any action.",
        "HALT": "Stop. Escalate the boundary condition to the decision owner.",
    }[gate["gate_result"]]

    return {
        "receipt_version": "0.1.0",
        "run_id": raw["run_id"],
        "run_timestamp": raw["run_timestamp"],
        "problem_statement": kwargs["intake"]["problem_statement"],
        "normalized_intake_hash": kwargs["normalized_hash"],
        "signals": kwargs["signals"],
        "classification": kwargs["classification"],
        "versions": {
            "policy_id": policy["policy_id"],
            "policy_version": policy["version"],
            "operator_registry_id": controls["registry"]["registry_id"],
            "operator_registry_version": controls["registry"]["version"],
            "operator_registry_sha256": controls["checksums"]["operator_registry_sha256"],
            "routing_policy_sha256": controls["checksums"]["routing_policy_sha256"],
        },
        "route": kwargs["route"],
        "option_set": [
            {"option_id": option["option_id"], "label": option["label"], "origin": option["origin"]}
            for option in sorted(kwargs["options"], key=lambda item: item["option_id"])
        ],
        "evidence_used": [
            {
                "evidence_id": record["evidence_id"],
                "source_type": record["source_type"],
                "authority": record["authority"],
                "quality": record["quality"],
                "independence_group": record["independence_group"],
                "verification_state": record["verification_state"],
                "untrusted_instruction_detected": record.get("untrusted_instruction_detected", False),
            }
            for record in sorted(kwargs["register"].values(), key=lambda item: item["evidence_id"])
        ],
        "operator_conclusions": [
            {
                "operator_id": conclusion["operator_id"],
                "operator_version": conclusion["operator_version"],
                "stage": conclusion["stage"],
                "status": conclusion["status"],
                "selection_basis": conclusion["selection_basis"],
                "selection_rationale": conclusion["selection_rationale"],
                "conclusions": [claim["statement"] for claim in conclusion["claims"]],
                "structured_payload_key": conclusion["structured_payload_key"],
                "structured_payload": conclusion["structured_payload"],
                "contract_violations": conclusion["contract_violations"],
            }
            for conclusion in kwargs["operator_conclusions"]
        ],
        "assumptions": kwargs["assumptions"],
        "contradictions": kwargs["contradictions"],
        "missing_evidence": kwargs["missing_evidence"],
        "confidence_by_operator": [
            {
                "operator_id": conclusion["operator_id"],
                "declared_confidence": conclusion["declared_confidence"],
                "effective_confidence": conclusion["effective_confidence"],
                "contributes_to_decision_confidence": conclusion["operator_id"]
                in policy["confidence_model"]["decision_confidence_contributors"],
            }
            for conclusion in kwargs["operator_conclusions"]
        ]
        + [
            {
                "operator_id": "convergent",
                "declared_confidence": "derived",
                "effective_confidence": convergence["decision_confidence"],
                "contributes_to_decision_confidence": True,
            }
        ],
        "convergence": {
            "ranking": convergence["ranking"],
            "selected_option_id": convergence["selected_option_id"],
            "rejected_alternatives": convergence["rejected_alternatives"],
            "tie_candidates": convergence["tie_candidates"],
            "selection_reason": convergence["selection_reason"],
            "decision_confidence": convergence["decision_confidence"],
            "decision_confidence_basis": convergence["decision_confidence_basis"],
            "decision_confidence_label": convergence["decision_confidence_label"],
            "thresholds_applied": convergence["thresholds_applied"],
        },
        "metacognitive_audit": audit_result,
        "gate": gate,
        "recommendation": kwargs["recommendation"],
        "recommendation_binding_hash": kwargs["receipt_binding"],
        "risks": risks,
        "authorization": kwargs["authorization"],
        "execution": kwargs["composition"],
        "review_requirements": review_requirements,
        "next_action": next_action,
        "stage_chain": kwargs["chain"].records,
        "stage_chain_head": kwargs["chain"].head,
        "partial_execution": kwargs["partial"],
        "record_id": f"{raw['run_id']}::{convergence['selected_option_id'] or 'NO_RECOMMENDATION'}",
    }
