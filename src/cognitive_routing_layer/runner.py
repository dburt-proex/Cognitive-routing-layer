"""Pipeline orchestration.

    intake -> classification -> route selection -> operator execution
    -> evidence and contradiction gate -> convergence -> metacognitive audit
    -> recommendation -> authorization gate -> decision receipt

The router is deterministic end to end. Operator *content* arrives through an
adapter so that a model can supply it later without any routing logic moving
into the model; v0.1 ships a fixture adapter so runs are byte-reproducible.
What the engine executes in either case is the operator *contract*: input
validation, required transformations, evidence binding, confidence ceilings,
and prohibited-behavior checks.
"""
from copy import deepcopy
from pathlib import Path
from typing import Any

from . import audit as audit_module
from . import authorization as auth_module
from . import contradiction as contradiction_module
from . import converge as converge_module
from . import evidence as evidence_module
from .classify import classify, extract_signals
from .contracts import enforce
from .intake import normalize_intake, intake_hash
from .io import digest, load_json
from .ledger import append_idempotent, seen_nonces
from .normalize import normalize_evidence_record
from .paths import SCHEMA_DIR
from .policy import load_controls
from .router import select_route
from .schema_validation import SchemaValidationError, load_and_validate
from .stages import StageChain


class RunError(RuntimeError):
    pass


def _effective(claim: dict[str, Any], register, policy, task_class, operator_id) -> dict[str, Any]:
    factors = policy["confidence_model"]["factors"]
    declared = claim.get("declared_confidence", "unknown")
    ceiling_info = evidence_module.ceiling(claim.get("evidence_refs", []), register, policy, task_class)
    declared_factor = factors.get(declared, 0.0)
    return {
        "claim_id": claim["claim_id"],
        "operator_id": operator_id,
        "statement": claim["statement"],
        "polarity": claim.get("polarity", "neutral"),
        "subject_ref": claim.get("subject_ref"),
        "evidence_refs": sorted(set(claim.get("evidence_refs", []))),
        "declared_confidence": declared,
        "declared_confidence_factor": declared_factor,
        "evidence_ceiling": ceiling_info["ceiling"],
        "effective_confidence": round(min(declared_factor, ceiling_info["ceiling"]), 6),
        "evidence_profile": ceiling_info,
    }


def run(run_input_path: Path, ledger_path: Path | None = None, verifier=None) -> dict[str, Any]:
    raw = load_json(run_input_path)
    load_and_validate(raw, SCHEMA_DIR / "run-input.schema.json")

    controls = load_controls()
    policy = controls["policy"]
    registry = controls["registry"]

    if raw.get("policy_version") != policy["version"] or raw.get("operator_registry_version") != registry["version"]:
        raise RunError("RCP-FAIL-VERSION-UNKNOWN: run input targets a different policy or operator registry version")

    run_id = raw["run_id"]
    run_timestamp = raw["run_timestamp"]

    intake = normalize_intake(deepcopy(raw["intake"]))
    normalized_hash = intake_hash(intake)

    signals = extract_signals(intake, policy)
    classification = classify(intake, policy)
    route = select_route(classification, signals, controls)

    records = [normalize_evidence_record(item) for item in deepcopy(raw.get("evidence_register", []))]
    for record in records:
        load_and_validate(record, SCHEMA_DIR / "evidence-record.schema.json")
    register = evidence_module.build_register(records)

    chain = StageChain()
    stage_contents: dict[int, dict[str, Any]] = {}

    def seal(stage: str, operator_id: str, version: str, status: str, content: dict[str, Any]) -> None:
        record = chain.append(stage, operator_id, version, status, content, run_timestamp)
        stage_contents[record["sequence"]] = content

    seal("INTAKE", "intake", "0.1.0", "COMPLETE", {"normalized_intake_hash": normalized_hash, "signals": signals})
    seal("CLASSIFY", "classifier", policy["version"], "COMPLETE", classification)

    if not route["route_supported"]:
        return _unsupported_receipt(
            raw, intake, normalized_hash, signals, classification, route, controls, chain, ledger_path
        )

    seal("ROUTE", "router", policy["version"], "COMPLETE", route)

    # The option set grows as the route runs. Options generated by an EXPLORE
    # operator join the set that CHALLENGE, FORECAST, and DECIDE work over,
    # which is what stops divergent from being decorative: a generated option
    # is ranked, challenged, and rejected on the record like any other.
    options = [{**option, "origin": "intake"} for option in intake["options"]]
    option_ids = {option["option_id"] for option in options}
    observation_ids = {item["observation_id"] for item in intake["observations"]}
    supplied = raw.get("operator_outputs", {})

    executed: list[str] = []
    violations: list[dict[str, Any]] = []
    claims: list[dict[str, Any]] = []
    operator_conclusions: list[dict[str, Any]] = []
    boundary_flags: set[str] = set()
    assumptions: list[dict[str, Any]] = []
    partial: list[dict[str, Any]] = []

    for step in route["operators"]:
        operator_id = step["operator_id"]
        if operator_id in {"convergent", "metacognitive"}:
            continue
        contract = controls["operators_by_id"][operator_id]
        payload = deepcopy(supplied.get(operator_id))

        if payload is None:
            partial.append({"operator_id": operator_id, "status": "NOT_EXECUTED", "detail": "no operator output supplied by the adapter"})
            seal(step["stage"], operator_id, contract["version"], "NOT_EXECUTED", {"operator_id": operator_id})
            continue

        ctx = {
            "policy": policy,
            "option_ids": option_ids,
            "observation_ids": observation_ids,
            "evidence_ids": set(register),
            "claim_ids": {claim["claim_id"] for claim in claims},
            "subject_ids": {item["hypothesis_id"] for item in payload.get("hypotheses", [])} | observation_ids,
        }
        # A structurally invalid payload is a contract violation, not a crash.
        # The route continues so the audit sees the whole picture, and the gate
        # forces REVIEW because a required operator did not meet its contract.
        found: list[dict[str, Any]] = []
        try:
            load_and_validate(payload, SCHEMA_DIR / "operator-output.schema.json")
        except SchemaValidationError as exc:
            found.append({"operator_id": operator_id, "code": "GLOBAL-SCHEMA", "detail": str(exc)})

        found.extend(enforce(operator_id, contract, payload, ctx))
        violations.extend(found)
        status = "CONTRACT_VIOLATION" if found else "COMPLETE"

        if contract["output_contract"]["produces_options"]:
            for generated in payload.get("options", []):
                if generated["option_id"] not in option_ids:
                    options.append({**generated, "origin": f"generated_by:{operator_id}"})
                    option_ids.add(generated["option_id"])

        ingestible = [
            claim
            for claim in payload.get("claims", [])
            if isinstance(claim, dict) and claim.get("claim_id") and claim.get("statement")
        ]
        if len(ingestible) != len(payload.get("claims", [])):
            found.append(
                {
                    "operator_id": operator_id,
                    "code": "GLOBAL-CLAIM-MALFORMED",
                    "detail": "a claim lacked a claim_id or statement and was not admitted to the run",
                }
            )
            violations.append(found[-1])
        resolved = [
            _effective(claim, register, policy, classification["task_class"], operator_id)
            for claim in ingestible
        ]
        claims.extend(resolved)
        executed.append(operator_id)
        boundary_flags.update(payload.get("boundary_flags", []))
        for assumption in payload.get("assumptions", []):
            assumptions.append({"operator_id": operator_id, "assumption": assumption, "treated_as": "missing_evidence"})

        conclusion = {
            "operator_id": operator_id,
            "operator_version": contract["version"],
            "stage": step["stage"],
            "status": status,
            "selection_basis": step["selection_basis"],
            "selection_rationale": step["selection_rationale"],
            "declared_confidence": payload.get("declared_confidence"),
            "effective_confidence": round(max((claim["effective_confidence"] for claim in resolved), default=0.0), 6),
            "structured_payload_key": contract["output_contract"]["structured_payload_key"],
            "structured_payload": payload.get(contract["output_contract"]["structured_payload_key"], []),
            "claims": resolved,
            "assumptions": payload.get("assumptions", []),
            "contract_violations": found,
        }
        operator_conclusions.append(conclusion)
        seal(step["stage"], operator_id, contract["version"], status, conclusion)

    contradictions = contradiction_module.detect(claims, policy)

    convergence = converge_module.converge(
        options, claims, register, contradictions, policy, classification["task_class"]
    )
    seal("DECIDE", "convergent", controls["operators_by_id"]["convergent"]["version"], "COMPLETE", convergence)
    executed.append("convergent")

    missing_evidence = _missing_evidence(convergence, assumptions, register)

    planned = [step["operator_id"] for step in route["operators"] if step["operator_id"] != "metacognitive"]
    audit_result = audit_module.run_audit(
        planned_operators=planned,
        executed_operators=executed,
        violations=violations,
        claims=claims,
        contradictions=contradictions,
        convergence=convergence,
        authorization={"derived_from_confidence": False},
        missing_evidence=missing_evidence,
        chain=chain,
        stage_contents=stage_contents,
        policy=policy,
    )
    seal("AUDIT", "metacognitive", controls["operators_by_id"]["metacognitive"]["version"], "COMPLETE", audit_result)
    executed.append("metacognitive")

    gate = _apply_gate(
        boundary_flags=sorted(boundary_flags),
        audit_result=audit_result,
        violations=violations,
        partial=partial,
        convergence=convergence,
        contradictions=contradictions,
        signals=signals,
        policy=policy,
    )

    recommendation = _recommendation(convergence, gate, options)
    receipt_binding = digest(
        {"run_id": run_id, "recommendation": recommendation["statement"], "option_id": recommendation["option_id"]}
    )

    authorization = auth_module.evaluate(
        requested_action=intake.get("requested_action"),
        authorization=raw.get("casa_authorization"),
        verifier=verifier or auth_module.UnavailableVerifier(),
        run_timestamp=run_timestamp,
        receipt_binding=receipt_binding,
        seen_nonces=seen_nonces(ledger_path),
    )
    composition = auth_module.compose_execution(
        gate_result=gate["gate_result"],
        evidence_sufficient=convergence["selected_option_id"] is not None,
        authorization_status=authorization["status"],
    )

    receipt = _receipt(
        raw=raw,
        controls=controls,
        intake=intake,
        normalized_hash=normalized_hash,
        signals=signals,
        classification=classification,
        route=route,
        register=register,
        operator_conclusions=operator_conclusions,
        claims=claims,
        assumptions=assumptions,
        contradictions=contradictions,
        missing_evidence=missing_evidence,
        convergence=convergence,
        audit_result=audit_result,
        gate=gate,
        recommendation=recommendation,
        options=options,
        receipt_binding=receipt_binding,
        authorization=authorization,
        composition=composition,
        partial=partial,
        chain=chain,
    )
    load_and_validate(receipt, SCHEMA_DIR / "decision-receipt.schema.json")
    receipt["ledger_receipt"] = append_idempotent(ledger_path, receipt)
    return receipt


